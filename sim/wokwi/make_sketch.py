"""Builds sim/wokwi/sketch.ino from the real firmware, with simulation-only settings.

Run after any firmware change:  .venv/bin/python sim/wokwi/make_sketch.py
The real board never uses these settings; they exist only so the virtual servo and
button work in Wokwi and commands can be typed by hand in its serial monitor.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
FIRMWARE = ROOT / 'firmware' / 'ghostgrip_uno'
OUT = pathlib.Path(__file__).resolve().parent

HEADER = """// GENERATED by sim/wokwi/make_sketch.py from firmware/ghostgrip_uno. Do not edit by hand.
// SIMULATION ONLY: servo and button enabled, watchdog relaxed to 60 s for typing commands.
#define SERVO_ENABLED 1
#define BUTTON_CONNECTED 1
#define WATCHDOG_MS 60000UL

"""

# Inline pins.h so the simulator needs only one file (easy to paste into wokwi.com).
pins = (FIRMWARE / 'pins.h').read_text().replace('#pragma once\n', '')
sketch = (FIRMWARE / 'ghostgrip_uno.ino').read_text().replace('#include "pins.h"\n', pins)
(OUT / 'sketch.ino').write_text(HEADER + sketch)
print('wrote', OUT / 'sketch.ino')
